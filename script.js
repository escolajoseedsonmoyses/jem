/* =====================================
   ESTADO DAS GALERIAS
===================================== */

const indicesAtuais = {

    equipe: 0,

    espacos: 0,

    acessibilidade: 0,

    premiacoes: 0,

    manna: 0,

    forum: 0,

    estacao: 0

};


/* =====================================
   FUNÇÕES DE CONTROLE
===================================== */

function atualizarGaleria(nomeGaleria) {

    const lista = galerias[nomeGaleria];

    const indice = indicesAtuais[nomeGaleria];

    const item = lista[indice];


    const imgEl =
        document.getElementById(`imagem-${nomeGaleria}`);

    const tituloEl =
        document.getElementById(`titulo-${nomeGaleria}`);

    const descEl =
        document.getElementById(`descricao-${nomeGaleria}`);

    const contEl =
        document.getElementById(`contador-${nomeGaleria}`);


    if (!imgEl || !item) return;


    imgEl.style.opacity = 0;


    setTimeout(() => {

        imgEl.src = item.imagem;

        imgEl.alt = item.titulo;


        if (tituloEl) {
            tituloEl.textContent = item.titulo;
        }


        if (descEl) {
            descEl.textContent = item.descricao;
        }


        if (contEl) {

            contEl.textContent =
                `${indice + 1} / ${lista.length}`;

        }


        imgEl.style.opacity = 1;

    }, 120);


    atualizarIndicadores(nomeGaleria);

}


/* =====================================
   MUDAR IMAGEM
===================================== */

function mudarImagem(nomeGaleria, direcao) {

    const lista = galerias[nomeGaleria];

    if (!lista) return;


    indicesAtuais[nomeGaleria] += direcao;


    if (indicesAtuais[nomeGaleria] < 0) {

        indicesAtuais[nomeGaleria] =
            lista.length - 1;

    }


    else if (
        indicesAtuais[nomeGaleria] >= lista.length
    ) {

        indicesAtuais[nomeGaleria] = 0;

    }


    atualizarGaleria(nomeGaleria);

}


/* =====================================
   IR PARA UMA IMAGEM ESPECÍFICA
===================================== */

function irParaImagem(nomeGaleria, indice) {

    indicesAtuais[nomeGaleria] = indice;

    atualizarGaleria(nomeGaleria);

}


/* =====================================
   INDICADORES
===================================== */

function atualizarIndicadores(nomeGaleria) {

    const conteinerIndicadores =
        document.getElementById(
            `indicadores-${nomeGaleria}`
        );


    if (!conteinerIndicadores) return;


    conteinerIndicadores.innerHTML = "";


    const lista =
        galerias[nomeGaleria];


    lista.forEach((_, index) => {

        const btn =
            document.createElement("button");


        btn.classList.add("indicador");


        if (
            index ===
            indicesAtuais[nomeGaleria]
        ) {

            btn.classList.add("ativo");

        }


        btn.setAttribute(
            "aria-label",
            `Ir para imagem ${index + 1} da galeria ${nomeGaleria}`
        );


        btn.onclick = () =>
            irParaImagem(
                nomeGaleria,
                index
            );


        conteinerIndicadores.appendChild(btn);

    });

}


/* =====================================
   INICIALIZAÇÃO
===================================== */

document.addEventListener(
    "DOMContentLoaded",
    () => {

        Object.keys(galerias).forEach(
            nomeGaleria => {

                atualizarGaleria(
                    nomeGaleria
                );

            }
        );

    }
);